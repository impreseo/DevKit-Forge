import { describe, it, expect } from 'vitest';
import { GITIGNORE_TEMPLATES, generateCombinedGitignore } from '../utils/gitignoreTemplates';

describe('Gitignore Templates & Generator', () => {
  it('contains essential developer ecosystems', () => {
    const ids = GITIGNORE_TEMPLATES.map((t) => t.id);
    expect(ids).toContain('node');
    expect(ids).toContain('python');
    expect(ids).toContain('rust');
    expect(ids).toContain('go');
    expect(ids).toContain('java');
    expect(ids).toContain('macos');
    expect(ids).toContain('windows');
    expect(ids).toContain('linux');
    expect(ids).toContain('vscode');
    expect(ids).toContain('jetbrains');
  });

  it('generates properly formatted combined output with headers', () => {
    const combined = generateCombinedGitignore(['node', 'vscode'], '*.secret\ncredentials.json');
    expect(combined).toContain('Generated by DevKit Forge');
    expect(combined).toContain('### Node.js / JavaScript / TypeScript ###');
    expect(combined).toContain('node_modules/');
    expect(combined).toContain('### Visual Studio Code ###');
    expect(combined).toContain('.vscode/*');
    expect(combined).toContain('### Custom Project Rules ###');
    expect(combined).toContain('*.secret');
  });

  it('handles empty selections gracefully', () => {
    const combined = generateCombinedGitignore([], '');
    expect(combined).toContain('Generated by DevKit Forge');
    expect(combined).not.toContain('### Node.js');
  });
});
