/**
 * Generate a combined .gitignore output string with clean markdown comments and separation.
 */
export function generateCombinedGitignore(
  selectedIds: string[],
  customRules: string = ''
): string {
  const parts: string[] = [
    `# =========================================================================`,
    `# Generated by DevKit Forge (.gitignore Generator)`,
    `# Client-side only • Zero server uploads`,
    `# =========================================================================\n`,
  ];

  for (const id of selectedIds) {
    const template = GITIGNORE_TEMPLATES.find((t) => t.id === id);
    if (template) {
      parts.push(`### ${template.name} ###\n${template.content.trim()}\n`);
    }
  }

  if (customRules.trim()) {
    parts.push(`### Custom Project Rules ###\n${customRules.trim()}\n`);
  }

  return parts.join('\n');
}
